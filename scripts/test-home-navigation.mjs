const active = page => page.locator('.home-phrase-wall:not(.home-ripple-out) .home-word.is-focused')
const category = (page, name) => page.waitForFunction(expected => document.querySelector('.home-navigation')?.getAttribute('data-category') === expected, name)
const settle = async (page, expected) => {
  if (expected) await active(page).filter({hasText:expected}).waitFor()
  else await page.waitForTimeout(100)
  await page.waitForFunction(() => {
  const focused = document.querySelector('.home-phrase-wall:not(.home-ripple-out) .home-word.is-focused')
  return focused && Number(getComputedStyle(focused.parentElement).getPropertyValue('--word-scale')) > .9999
  })
}
